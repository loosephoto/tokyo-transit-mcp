// 正式路線名の存在チェック用
const linesMatch = src.match(/const RAILWAY_LINES = \{([\s\S]*?)\n\};/);
const lineNames = new Set([...linesMatch[1].matchAll(/^\s*'([^']+)':/gm)].map(x => x[1]));

const mapMatch = src.match(/const RAILWAY_NAME_MAP = \{([\s\S]*?)\n\};/);
const body = mapMatch[1];
const existingKeys = new Set();
for (const k of body.matchAll(/'([^']+)'\s*:/g)) existingKeys.add(k[1]);

// 既存マップの値（正式名）も収集（既存キーの値と衝突しないか）
const existingVals = new Set();
for (const v of body.matchAll(/:\s*'([^']+)'/g)) existingVals.add(v[1]);

let added = 0;
const skipped = [];
const lines = [];
for (const [key, val] of ADD) {
  if (existingKeys.has(key)) { skipped.push(key + '(既存キー)'); continue; }
  if (!lineNames.has(val)) { skipped.push(key + '(→不明な正式名:' + val + ')'); continue; }
  lines.push(`  '${key}': '${val}',`);
  existingKeys.add(key);
  added++;
}
if (added === 0) { console.log('追加すべき新規エイリアスなし。スキップ:', skipped.join(', ')); process.exit(0); }

const anchor = "  ' JR ': 'jr-east', 'JR東日本': 'jr-east', 'JR西日本': 'jr-west',\n";
if (!src.includes(anchor)) { console.error('ANCHOR NOT FOUND'); process.exit(1); }
const insert = '\n  // 2026-08 全路線の略称・表記揺れエイリアス（v2.25.3 充実化）\n' + lines.join('\n') + '\n';
src = src.replace(anchor, anchor + insert);
fs.writeFileSync('src/data/station-names.mjs', src);
console.log('追加したエイリアス数:', added);
if (skipped.length) console.log('スキップ:', skipped.join(', '));
